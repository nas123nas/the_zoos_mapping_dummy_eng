  const labels = Object.keys(messages).filter(key => !/^[개건종일외]$/u.test(key)).sort((a, b) => b.length - a.length);
  const phrases = new RegExp(labels.map(key => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "gu");
  const hasHangul = /[가-힣]/u;

  function translate(value) {
    if (typeof value !== "string" || !hasHangul.test(value)) return value;
    return value
      .replace(/(\d{2})업체/gu, "Vendor $1")
      .replace(/([\d,.]+)\s*개\/일/gu, "$1 units/day")
      .replace(/(\d[\d,.]*)\s*개\s*파일/gu, "$1 file(s)")
      .replace(/(\d[\d,.]*)\s*(품목|개|건|종|일)(?![가-힣])/gu, (_, count, unit) => {
        const noun = { 품목: "item", 개: "unit", 건: "record", 종: "type", 일: "day" }[unit];
        return `${count} ${noun}${count === "1" ? "" : "s"}`;
      })
      .replace(phrases, key => messages[key]);
  }

  window.EnglishDemo = { translate };

  const attributes = ["aria-label", "aria-description", "title", "placeholder", "alt"];

  function translateText(node) {
    if (node.parentElement?.closest("script, style, textarea, [contenteditable]")) return;
    const text = translate(node.data);
    if (text !== node.data) node.data = text;
  }

  function translateAttributes(element) {
    for (const name of attributes) {
      const original = element.getAttribute(name);
      const localized = translate(original);
      if (localized !== original) element.setAttribute(name, localized);
    }
  }

  function translateTree(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      translateText(node);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    const elements = document.createTreeWalker(node, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    do {
      const child = elements.currentNode;
      if (child.nodeType === Node.TEXT_NODE) translateText(child);
      else translateAttributes(child);
    } while (elements.nextNode());
  }

  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === "attributes") translateAttributes(record.target);
      else if (record.type === "characterData") translateText(record.target);
      else {
        const option = record.target.closest?.("option");
        if (option && !option.hasAttribute("value")) option.value = option.text;
        for (const node of record.addedNodes) {
          const options = node.querySelectorAll?.("option:not([value])") || [];
          for (const child of options) child.value = child.text;
          if (node.matches?.("option:not([value])")) node.value = node.text;
          translateTree(node);
        }
      }
    }
  });

  function start() {
    for (const option of document.querySelectorAll("option:not([value])")) option.value = option.text;
    translateTree(document.body);
    observer.observe(document.body, {
      subtree: true, childList: true, characterData: true,
      attributes: true, attributeFilter: attributes,
    });
  }

  if (document.body) start();
  else document.addEventListener("DOMContentLoaded", start, { once: true });

  for (const method of ["alert", "confirm", "prompt"]) {
    const original = window[method].bind(window);
    window[method] = (message, ...rest) => original(translate(message), ...rest);
  }
